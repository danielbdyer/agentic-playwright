/**
 * Finding and starting the customer's Playwright. Tesseract is not in the
 * runtime path: the specs run under the Playwright the workspace installed,
 * with the workspace's own config when it has one. Only when it has neither
 * does Tesseract supply a fallback (its own @playwright/test dependency, and
 * a minimal config under .tesseract/tmp/).
 */
import { spawn, type ChildProcess } from 'node:child_process';
import { createRequire } from 'node:module';
import path from 'node:path';
import { ToolError } from '../core/errors.js';
import { exists, writeFileAtomic } from '../core/fsio.js';
import type { Profile } from '../workspace/profiles.js';
import { resolveInside, type Workspace } from '../workspace/workspace.js';

export interface PlaywrightCli {
  /** Absolute path of @playwright/test/cli.js. */
  readonly cli: string;
  /** Where it came from: the workspace's node_modules, or this package's dependency. */
  readonly source: 'workspace' | 'package';
  /** node_modules directory to put on NODE_PATH so CommonJS specs can import @playwright/test (package fallback only). */
  readonly nodePath?: string;
}

const resolvePackageJson = (from: string): string | null => {
  try {
    return createRequire(from).resolve('@playwright/test/package.json');
  } catch {
    return null;
  }
};

/** @playwright/test's CLI, from the workspace first, then from this package's dependency. */
export const resolvePlaywrightCli = (workspace: Workspace): PlaywrightCli => {
  const fromWorkspace = resolvePackageJson(path.join(workspace.paths.root, 'package.json'));
  if (fromWorkspace !== null) return { cli: path.join(path.dirname(fromWorkspace), 'cli.js'), source: 'workspace' };
  const fromPackage = resolvePackageJson(import.meta.url);
  if (fromPackage === null) {
    throw new ToolError('unavailable', '@playwright/test is not installed in the workspace (npm install -D @playwright/test)');
  }
  const pkgDir = path.dirname(fromPackage);
  return { cli: path.join(pkgDir, 'cli.js'), source: 'package', nodePath: path.dirname(path.dirname(pkgDir)) };
};

const CONFIG_NAMES = ['playwright.config.ts', 'playwright.config.js', 'playwright.config.mjs', 'playwright.config.mts', 'playwright.config.cjs', 'playwright.config.cts'];

/** The customer's Playwright config: workspace.config.playwrightConfig, else playwright.config.* at the root, else null. */
export const findCustomerConfig = async (workspace: Workspace): Promise<string | null> => {
  if (workspace.config.playwrightConfig !== null) {
    const configured = resolveInside(workspace, workspace.config.playwrightConfig);
    if (!(await exists(configured))) {
      throw new ToolError('not-found', `configured Playwright config ${workspace.config.playwrightConfig} does not exist`);
    }
    return configured;
  }
  for (const name of CONFIG_NAMES) {
    const candidate = path.join(workspace.paths.root, name);
    if (await exists(candidate)) return candidate;
  }
  return null;
};

/** The `use` options a profile contributes when Tesseract writes the config (baseURL, storage state, viewport, locale). */
export const profileUse = (workspace: Workspace, profile: Profile | null): Readonly<Record<string, unknown>> =>
  profile === null
    ? {}
    : {
        baseURL: profile.baseURL,
        ...(profile.storageStatePath !== undefined ? { storageState: resolveInside(workspace, profile.storageStatePath) } : {}),
        ...(profile.viewport !== undefined ? { viewport: profile.viewport } : {}),
        ...(profile.locale !== undefined ? { locale: profile.locale } : {}),
        ...(profile.timezoneId !== undefined ? { timezoneId: profile.timezoneId } : {}),
      };

/**
 * The minimal config for a workspace without one: testDir = the tests
 * directory, the profile's baseURL (and storage state), traces kept on
 * failure. Plain ESM with no imports, so it loads whatever the workspace's
 * module type and wherever @playwright/test lives.
 */
export const minimalConfigSource = (testDir: string, use: Readonly<Record<string, unknown>>): string =>
  [
    '// Generated by tesseract-qa for one test.run: the workspace has no Playwright config.',
    `export default ${JSON.stringify({ testDir, use: { ...use, trace: 'retain-on-failure' } }, null, 2)};`,
    '',
  ].join('\n');

export const writeMinimalConfig = async (file: string, workspace: Workspace, profile: Profile | null): Promise<string> => {
  await writeFileAtomic(file, minimalConfigSource(workspace.paths.tests, profileUse(workspace, profile)));
  return file;
};

const escapeForFilter = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Playwright's file filter (a case-insensitive regular expression over the absolute path) for exactly this file. */
export const fileFilter = (absolute: string): string => `${escapeForFilter(absolute)}$`;

/** Playwright's file filter for every *.spec.ts below a directory. */
export const specsUnder = (directory: string): string => `^${escapeForFilter(directory.endsWith(path.sep) ? directory : `${directory}${path.sep}`)}.*\\.spec\\.ts$`;

export interface ChildRun {
  readonly child: ChildProcess;
  /** Resolves with the exit code (null when killed by a signal). Never rejects. */
  readonly exited: Promise<number | null>;
  /** The last ~16 KB of stdout and stderr. */
  readonly output: () => string;
  /** Whether the process has exited. */
  readonly done: () => boolean;
  /** Kill the process group (Playwright's workers and browsers with it). */
  readonly kill: (signal?: NodeJS.Signals) => void;
  /**
   * Signal whatever is left of the process group, also after the runner
   * itself exited: Playwright's workers ignore SIGTERM (the runner stops them
   * gracefully), so a runner that exits on SIGTERM can leave a worker, and
   * its browser, running on as orphans.
   */
  readonly killGroup: (signal: NodeJS.Signals) => void;
}

const TAIL_BYTES = 16 * 1024;

/** Start `node <cli> test …` in the workspace root. The process leads its own group so a kill takes its browsers along. */
export const startPlaywright = (cli: string, args: readonly string[], cwd: string, env: NodeJS.ProcessEnv): ChildRun => {
  const posix = process.platform !== 'win32';
  const child = spawn(process.execPath, [cli, 'test', ...args], { cwd, env, stdio: ['ignore', 'pipe', 'pipe'], detached: posix });
  let tail = '';
  let finished = false;
  const collect = (chunk: Buffer): void => {
    tail = `${tail}${chunk.toString('utf8')}`;
    if (tail.length > TAIL_BYTES) tail = tail.slice(-TAIL_BYTES);
  };
  child.stdout?.on('data', collect);
  child.stderr?.on('data', collect);
  const exited = new Promise<number | null>((resolve) => {
    child.once('error', (error) => {
      collect(Buffer.from(`\n${error.message}\n`));
      finished = true;
      resolve(null);
    });
    child.once('close', (code) => {
      finished = true;
      resolve(code);
    });
  });
  const kill = (signal: NodeJS.Signals = 'SIGTERM'): void => {
    if (finished || child.pid === undefined) return;
    try {
      if (posix) process.kill(-child.pid, signal);
      else child.kill(signal);
    } catch {
      try {
        child.kill(signal);
      } catch {
        // already gone
      }
    }
  };
  const killGroup = (signal: NodeJS.Signals): void => {
    if (child.pid === undefined) return;
    try {
      if (posix) process.kill(-child.pid, signal);
      else if (!finished) child.kill(signal);
    } catch {
      // nothing left in the group
    }
  };
  return { child, exited, output: () => tail, done: () => finished, kill, killGroup };
};

/**
 * Stop a child: SIGTERM, then SIGKILL after `graceMs`, and SIGKILL to the
 * rest of its process group once the runner is gone (orphaned workers and
 * browsers). Resolves when the runner has exited.
 */
export const stopPlaywright = async (run: ChildRun, graceMs = 3000): Promise<void> => {
  if (!run.done()) {
    run.kill('SIGTERM');
    const timer = new Promise<'timeout'>((resolve) => setTimeout(() => resolve('timeout'), graceMs).unref());
    if ((await Promise.race([run.exited, timer])) === 'timeout') run.kill('SIGKILL');
    await Promise.race([run.exited, new Promise((resolve) => setTimeout(resolve, graceMs).unref())]);
  }
  run.killGroup('SIGKILL');
};
