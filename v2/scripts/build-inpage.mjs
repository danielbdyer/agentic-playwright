#!/usr/bin/env node
/**
 * Bundles src/observe/in-page/walker.ts into one self-contained string and
 * writes it to src/observe/in-page/bundle.generated.ts.
 *
 * Why a string: the walker runs inside the customer's page. Handing
 * Playwright a function literal lets the host's transpiler (tsx keepNames,
 * coverage instrumentation) inject helpers like __name into the body, which
 * then throw in the page. A prebuilt IIFE evaluated as a string expression
 * is immune to that, and its top-level names stay local to the evaluation.
 *
 *   node scripts/build-inpage.mjs            write the generated file
 *   node scripts/build-inpage.mjs --check    exit 1 when the generated file is stale
 *   --out <file>                             alternate output (tests use it)
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, rename } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'src/observe/in-page/walker.ts');
const defaultOut = path.join(root, 'src/observe/in-page/bundle.generated.ts');

const args = process.argv.slice(2);
const check = args.includes('--check');
const outIndex = args.indexOf('--out');
const out = outIndex >= 0 && args[outIndex + 1] ? path.resolve(args[outIndex + 1]) : defaultOut;

const bundle = async () => {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: '__tesseractInPage',
    platform: 'browser',
    target: 'es2020',
    minify: false,
    keepNames: false,
    sourcemap: false,
    legalComments: 'none',
    charset: 'ascii',
    logLevel: 'silent',
  });
  const file = result.outputFiles[0];
  if (file === undefined) throw new Error('esbuild produced no output');
  return file.text.replace(/\r\n/g, '\n');
};

/** A template literal keeps the bundle readable in review; escape the three characters that matter. */
const templateLiteral = (text) => `\`${text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``;

const render = (code) => {
  const hash = `sha256:${createHash('sha256').update(code).digest('hex')}`;
  return [
    '// GENERATED by scripts/build-inpage.mjs from src/observe/in-page/walker.ts. Do not edit.',
    '// Rebuild with `npm run build:inpage`; `node scripts/build-inpage.mjs --check` fails when this file is stale.',
    '/* eslint-disable */',
    '',
    `export const IN_PAGE_BUNDLE_HASH = '${hash}';`,
    '',
    `export const IN_PAGE_BUNDLE: string = ${templateLiteral(code)};`,
    '',
  ].join('\n');
};

const main = async () => {
  const content = render(await bundle());
  if (check) {
    const current = await readFile(out, 'utf8').catch(() => null);
    if (current !== content) {
      process.stderr.write(`stale: ${path.relative(root, out)} does not match ${path.relative(root, entry)}; run npm run build:inpage\n`);
      process.exit(1);
    }
    process.stdout.write(`up to date: ${path.relative(root, out)}\n`);
    return;
  }
  const temp = `${out}.${process.pid}.tmp`;
  await writeFile(temp, content, 'utf8');
  await rename(temp, out);
  process.stdout.write(`wrote ${path.relative(root, out)} (${content.length} bytes)\n`);
};

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.stack ?? error.message : String(error)}\n`);
  process.exit(2);
});
