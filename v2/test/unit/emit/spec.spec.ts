const base: SpecInput = { testCase: testCase10001, steps: steps10001, catalogs: [policySearchCatalog], area: 'policy' };

/** A one-step case on the policy-search screen, for exercising a single verb or assertion. */
const oneStep = (step: Partial<ResolvedStep>, testCase: Partial<TestCase> = {}, catalogs: readonly ScreenCatalog[] = [policySearchCatalog]) =>
  renderSpec({
    testCase: {
      ...testCase10001,
      steps: [{ index: 1, stepIdentifier: '7', action: 'Do the thing', expected: '' }],
      ...testCase,
    },
    steps: [{ index: 1, stepIdentifier: '7', actionText: 'Do the thing', expectedText: '', verb: 'click', ...step }],
    catalogs,
  });

const bodyOf = (text: string): string => {
  const start = text.indexOf("await test.step('Do the thing', async () => {");
  return text.slice(start, text.indexOf('\n  });', start) + 6);
};

const stepBody = (step: Partial<ResolvedStep>, testCase: Partial<TestCase> = {}, catalogs?: readonly ScreenCatalog[]): string =>
  bodyOf(oneStep(step, testCase, catalogs).text)
    .split('\n')
    .slice(1, -1)
    .map((line) => line.trim())
    .join('\n');

const errorOf = (fn: () => unknown): { family: string; message: string } => {
  try {
    fn();
  } catch (error) {
    if (isToolError(error)) return { family: error.family, message: error.message };
    throw error;
  }
  throw new Error('expected a ToolError');
};

