import { describe, expect, it } from 'vitest';
import { isToolError } from '../../../src/core/errors.js';
import { memberTable, overriddenMembers, renderOverridesScaffold, renderPageObject } from '../../../src/emit/index.js';
import { facet, policySearchCatalog, policySearchFacets } from './fixtures.js';

const GOLDEN_PAGE = `// Generated by Tesseract from .tesseract/catalog/policy-search.yaml — edit facets there, or members in policy-search.page.overrides.ts;
// regions marked tesseract:keep survive regeneration.
// tesseract:generated sha256:698e5a7a4c6f
import type { Locator, Page } from '@playwright/test';

export class PolicySearchPage {
  readonly page: Page;

  constructor(page: Page) {
    this.page = page;
  }

  /** route policy-search — opens PolicySearch (relative to baseURL) and waits for the main landmark */
  async goto(): Promise<void> {
    await this.page.goto('PolicySearch');
    await this.page.getByRole('main').waitFor();
  }

  /** facet policy-search:heading — content-named heading in the banner landmark; fallback: this.page.getByText('Policy Search', { exact: true }) (12/12) */
  get heading(): Locator {
    return this.page.getByRole('heading', { name: 'Policy Search', exact: true });
  }

  /** facet policy-search:policy-number-input — placeholder-named textbox in the search landmark; fallback: this.page.getByPlaceholder('Search Policy', { exact: true }) (12/12) */
  get policyNumberInput(): Locator {
    return this.page.getByRole('search').getByRole('textbox', { name: 'Search Policy', exact: true });
  }

  /** facet policy-search:search-button — content-named button in the search landmark */
  get searchButton(): Locator {
    return this.page.getByRole('search').getByRole('button', { name: 'Search', exact: true });
  }

  /** facet policy-search:results-table — row selected by the text it contains (policyNumber) */
  resultRow(policyNumber: string): Locator {
    return this.page.getByRole('row').filter({ hasText: policyNumber });
  }
}
`;

const render = (facets = policySearchFacets, overrides: string | null = null, route = policySearchCatalog.route) =>
  renderPageObject('policy-search', route, facets, overrides);

describe('renderPageObject', () => {
  it('renders the §5.5 page object exactly (golden)', () => {
    const page = render();
    expect(page.path).toBe('pages/policy-search.page.ts');
    expect(page.className).toBe('PolicySearchPage');
    expect(page.text).toBe(GOLDEN_PAGE);
    expect(page.members).toEqual({
      'policy-search:heading': 'heading',
      'policy-search:policy-number-input': 'policyNumberInput',
      'policy-search:search-button': 'searchButton',
      'policy-search:results-table': 'resultRow',
    });
  });

  it('uses no parameter properties (works under erasableSyntaxOnly / Node type stripping)', () => {
    expect(render().text).not.toMatch(/constructor\((private|protected|public|readonly)/);
  });

  it('strips a leading slash from relative routes and keeps absolute ones; waits for main only when known', () => {
    const relative = render(policySearchFacets, null, { url: '/PolicySearch' });
    expect(relative.text).toContain("await this.page.goto('PolicySearch');");
    expect(relative.text).not.toContain("getByRole('main').waitFor()");
    const absolute = render(policySearchFacets, null, { url: 'https://qa.example.com/App/PolicySearch', landmarks: ['main'] });
    expect(absolute.text).toContain("/** route policy-search — opens https://qa.example.com/App/PolicySearch and waits for the main landmark */");
    expect(absolute.text).toContain("await this.page.goto('https://qa.example.com/App/PolicySearch');");
    expect(render(policySearchFacets, null, null).text).not.toContain('goto');
  });

  it('marks stale facets @deprecated, omits retired and route facets, and notes facets without a locator', () => {
    const facets = [
      facet({ id: 'policy-search:status', status: 'stale', role: 'combobox', tag: 'select', locators: [{ strategy: 'label', value: 'Status', health: '1/6' }] }),
      facet({ id: 'policy-search:gone', status: 'retired', locators: [{ strategy: 'text', value: 'Gone' }] }),
      facet({ id: 'policy-search:route', kind: 'route', locators: [] }),
      facet({ id: 'policy-search:pending', locators: [] }),
    ];
    const text = render(facets).text;
    expect(text).toContain(
      [
        '  /**',
        '   * facet policy-search:status — combobox',
        '   * @deprecated stale: this locator stopped resolving reliably; re-observe the policy-search screen to repair the facet.',
        '   */',
        '  get status(): Locator {',
      ].join('\n'),
    );
    expect(text).not.toContain('gone');
    expect(text).not.toContain('policy-search:route');
    expect(text).toContain('  // facet policy-search:pending has no locator yet; observe the policy-search screen to give it one');
  });

  it('emits a select helper for custom comboboxes', () => {
    const region = facet({ id: 'policy-search:region', role: 'combobox', tag: 'div', namingSource: 'aria-label', locators: [{ strategy: 'role-name', role: 'combobox', name: 'Region' }] });
    const text = render([region]).text;
    expect(text).toContain(
      [
        '  /** select policy-search:region — custom combobox: opens it, then picks the option by its accessible name */',
        '  async selectRegion(value: string): Promise<void> {',
        '    await this.region.click();',
        "    await this.page.getByRole('option', { name: value, exact: true }).click();",
        '  }',
      ].join('\n'),
    );
  });

  it('names members from facet.member, then the local id; collisions and reserved names get suffixes', () => {
    const facets = [
      facet({ id: 'policy-search:save', member: 'saveButton', locators: [{ strategy: 'text', value: 'Save' }] }),
      facet({ id: 'policy-search:save-button', locators: [{ strategy: 'text', value: 'Save it' }] }),
      facet({ id: 'policy-search:page', locators: [{ strategy: 'text', value: 'Page' }] }),
      facet({ id: 'policy-search:goto', locators: [{ strategy: 'text', value: 'Go' }] }),
      facet({ id: 'policy-search:class', locators: [{ strategy: 'role-name', role: 'link', name: '{class}' }] }),
      facet({ id: 'policy-search:order-rows', kind: 'row', locators: [{ strategy: 'row-text', value: '{orderId}' }] }),
    ];
    const names = [...memberTable(facets).values()].map((m) => [m.name, m.params]);
    expect(names).toEqual([
      ['saveButton', []],
      ['saveButton2', []],
      ['pageElement', []],
      ['gotoElement', []],
      ['class', ['classValue']],
      ['orderRow', ['orderId']],
    ]);
    const text = render(facets).text;
    expect(text).toContain("  class(classValue: string): Locator {\n    return this.page.getByRole('link', { name: classValue, exact: true });");
  });

  it('refuses facets of another screen', () => {
    try {
      renderPageObject('policy-search', null, [facet({ id: 'login:x', locators: [{ strategy: 'text', value: 'x' }] })], null);
      throw new Error('expected a ToolError');
    } catch (error) {
      expect(isToolError(error) && error.family).toBe('invalid-input');
    }
  });
});

describe('renderPageObject — overrides by extension', () => {
  const overrides = `import type { Locator, Page } from '@playwright/test';

export class PolicySearchPageOverrides {
  readonly page: Page;

  constructor(page: Page) {
    this.page = page;
  }

  get searchButton(): Locator {
    const heading = this.page.getByRole('heading');
    return this.page.getByRole('button', { name: 'Search' });
  }

  async goto(): Promise<void> {
    await this.page.goto('PolicySearch?debug=1');
  }
}
`;

  it('finds class-level members only (not statements inside methods)', () => {
    expect([...overriddenMembers(overrides)].sort()).toEqual(['goto', 'page', 'searchButton']);
  });

  it('extends the overrides class, inherits page and the constructor, and skips overridden members', () => {
    const text = render(policySearchFacets, overrides).text;
    expect(text).toContain("import type { Locator } from '@playwright/test';");
    expect(text).toContain("import { PolicySearchPageOverrides } from './policy-search.page.overrides';");
    expect(text).toContain('export class PolicySearchPage extends PolicySearchPageOverrides {');
    expect(text).not.toContain('constructor');
    expect(text).not.toContain('readonly page');
    expect(text).toContain('  // goto (route policy-search) is defined in policy-search.page.overrides.ts');
    expect(text).toContain('  // searchButton (facet policy-search:search-button) is defined in policy-search.page.overrides.ts');
    expect(text).toContain('  get policyNumberInput(): Locator {');
    expect(text).not.toContain('get searchButton');
  });

  it('an overrides file without the expected class is a conflict', () => {
    try {
      render(policySearchFacets, 'export class Something {}\n');
      throw new Error('expected a ToolError');
    } catch (error) {
      expect(isToolError(error) && error.family).toBe('conflict');
    }
  });

  it('offers a scaffold that defines the expected class', () => {
    const scaffold = renderOverridesScaffold('policy-search');
    expect(scaffold).toContain('export class PolicySearchPageOverrides {');
    expect(() => render(policySearchFacets, scaffold)).not.toThrow();
  });
});
