import { describe, expect, it } from 'vitest';
import { isToolError } from '../../../src/core/errors.js';
import { paramEnvName, renderFlow } from '../../../src/emit/index.js';
import type { FlowRecording } from '../../../src/emit/index.js';
import { facet, loginCatalog, loginFacets, loginRecording, policySearchCatalog, policySearchFacets } from './fixtures.js';

const GOLDEN_LOGIN = `// Generated by Tesseract from .tesseract/flows/login.json — record the flow again, or edit facets in .tesseract/catalog/;
// regions marked tesseract:keep survive regeneration.
// tesseract:generated sha256:dc883943cfa6
import type { Page } from '@playwright/test';
import { LoginPage } from '../pages/login.page';

export interface LoginParams {
  readonly username: string;
  readonly password: string;
}

/** Reads a flow parameter from the environment, so secrets never live in the repository. */
export function requireEnv(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === '') {
    throw new Error(\`Set the environment variable \${name} to run this flow.\`);
  }
  return value;
}

/** Flow login, recorded with Tesseract: 4 steps, parameters username, password (secret). */
export async function login(page: Page, params: LoginParams): Promise<void> {
  const loginPage = new LoginPage(page);
  // step 1 — navigate https://qa.example.com/App/Login
  await loginPage.goto();
  // step 2 — fill login:username-input
  await loginPage.usernameInput.fill(params.username);
  // step 3 — fill login:password-input
  await loginPage.passwordInput.fill(params.password);
  // step 4 — click login:log-in-button
  await loginPage.logInButton.click();
}
`;

const byId = new Map([...loginFacets, ...policySearchFacets].map((f) => [f.id, f]));
const routes = { login: loginCatalog.route, 'policy-search': policySearchCatalog.route };

describe('renderFlow', () => {
  it('renders a recorded login flow over the page objects (golden)', () => {
    const flow = renderFlow(loginRecording, byId, routes);
    expect(flow.path).toBe('flows/login.ts');
    expect(flow.functionName).toBe('login');
    expect(flow.screens).toEqual(['login']);
    expect(flow.facetsUsed).toEqual(['login:username-input', 'login:password-input', 'login:log-in-button']);
    expect(flow.text).toBe(GOLDEN_LOGIN);
  });

  it('accepts a record of facets and routes as well as maps', () => {
    const record = Object.fromEntries(byId);
    expect(renderFlow(loginRecording, record, new Map(Object.entries(routes))).text).toBe(GOLDEN_LOGIN);
  });

  it('a flow without parameters takes Record<string, never>, has no requireEnv, and spans screens', () => {
    const recording: FlowRecording = {
      name: 'policy-search-happy-path',
      params: [],
      steps: [
        { index: 1, action: 'navigate', screen: 'policy-search', url: 'https://qa.example.com/App/PolicySearch' },
        { index: 2, action: 'fill', facetId: 'policy-search:policy-number-input', screen: 'policy-search', value: { literal: 'POL-001' }, url: 'u' },
        { index: 3, action: 'press', facetId: 'policy-search:policy-number-input', screen: 'policy-search', value: { literal: 'Enter' }, url: 'u' },
        { index: 4, action: 'click', facetId: 'policy-search:results-table', screen: 'policy-search', value: { literal: 'POL-001' }, url: 'u' },
        { index: 5, action: 'navigate', screen: 'reports', url: 'https://qa.example.com/App/Reports' },
        { index: 6, action: 'press', screen: 'reports', value: { literal: 'Escape' }, url: 'u' },
      ],
    };
    const flow = renderFlow(recording, byId, routes);
    expect(flow.path).toBe('flows/policy-search-happy-path.ts');
    expect(flow.text).toContain('export type PolicySearchHappyPathParams = Record<string, never>;');
    expect(flow.text).not.toContain('requireEnv');
    expect(flow.text).toContain('export async function policySearchHappyPath(page: Page, _params: PolicySearchHappyPathParams): Promise<void> {');
    expect(flow.text).toContain("  await policySearch.policyNumberInput.fill('POL-001');");
    expect(flow.text).toContain("  await policySearch.policyNumberInput.press('Enter');");
    expect(flow.text).toContain("  await policySearch.resultRow('POL-001').click();");
    expect(flow.text).toContain("  await page.goto('https://qa.example.com/App/Reports');");
    expect(flow.text).toContain("  await page.keyboard.press('Escape');");
  });

  it('selects natively or through the combobox helper', () => {
    const native = facet({ id: 'login:role', role: 'combobox', tag: 'select', locators: [{ strategy: 'label', value: 'Role' }] });
    const custom = facet({ id: 'login:tenant', role: 'combobox', tag: 'div', locators: [{ strategy: 'label', value: 'Tenant' }] });
    const facets = new Map([...byId, [native.id, native], [custom.id, custom]]);
    const recording: FlowRecording = {
      name: 'pick',
      params: [{ name: 'tenant', secret: false }],
      steps: [
        { index: 1, action: 'select', facetId: native.id, screen: 'login', value: { literal: 'Admin' }, url: 'u' },
        { index: 2, action: 'select', facetId: custom.id, screen: 'login', value: { param: 'tenant' }, url: 'u' },
      ],
    };
    const text = renderFlow(recording, facets, routes).text;
    expect(text).toContain("  await login.role.selectOption('Admin');");
    expect(text).toContain('  await login.selectTenant(params.tenant);');
  });

  it('refuses unknown facets, unknown parameters, bad names and unknown actions', () => {
    const family = (recording: FlowRecording): string => {
      try {
        renderFlow(recording, byId, routes);
        return 'none';
      } catch (error) {
        return isToolError(error) ? error.family : 'thrown';
      }
    };
    expect(family({ ...loginRecording, steps: [{ index: 1, action: 'click', facetId: 'login:nope', screen: 'login', url: 'u' }] })).toBe('not-found');
    expect(family({ ...loginRecording, steps: [{ index: 1, action: 'fill', facetId: 'login:username-input', screen: 'login', value: { param: 'nope' }, url: 'u' }] })).toBe('invalid-input');
    expect(family({ ...loginRecording, name: 'Log In' })).toBe('invalid-input');
    expect(family({ ...loginRecording, steps: [{ index: 1, action: 'drag', facetId: 'login:username-input', screen: 'login', url: 'u' }] })).toBe('invalid-input');
  });

  it('names the environment variables flow parameters are read from', () => {
    expect(paramEnvName('password')).toBe('TESSERACT_PARAM_PASSWORD');
    expect(paramEnvName('api-key')).toBe('TESSERACT_PARAM_API_KEY');
  });
});
